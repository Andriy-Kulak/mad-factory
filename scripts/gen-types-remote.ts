/**
 * Generates src/db/database.types.ts from the LIVE Supabase project using the
 * Supabase CLI (`supabase gen types`), as a cross-check on the PGlite generator.
 * Needs SUPABASE_DB_URL to be reachable from this machine: Supabase's direct
 * host is IPv6-only, so on IPv4-only networks use the Session pooler URI
 * (Project Settings -> Database -> Connection string -> Session pooler).
 *
 *   pnpm db:types:remote
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { requireEnv } from "../src/lib/env.ts";
import { normalizeDbUrl } from "../src/lib/db-url.ts";

const url = normalizeDbUrl(requireEnv("SUPABASE_DB_URL"));
const r = spawnSync("pnpm", ["dlx", "supabase@latest", "gen", "types", "typescript", "--db-url", url, "--schema", "public"], {
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
if (r.status !== 0 || !r.stdout.includes("export type Database")) {
  console.error("supabase gen types failed. If the error mentions ECONNREFUSED on an IPv6 address, switch SUPABASE_DB_URL to the Session pooler URI.");
  console.error(r.stderr.replace(/postgres(ql)?:\/\/\S+/g, "<db-url>").split("\n").filter((l) => !l.startsWith("Progress")).slice(-5).join("\n"));
  process.exit(1);
}
writeFileSync("src/db/database.types.ts", "// Generated by `pnpm db:types:remote` from the live Supabase project.\n" + r.stdout);
console.log("wrote src/db/database.types.ts from the live project");
