/**
 * Generates src/db/database.types.ts from supabase/migrations by applying them
 * to an in-memory PGlite Postgres and introspecting information_schema.
 * No network or Supabase CLI needed; output mirrors `supabase gen types` shape.
 *
 *   pnpm db:types          # write the file
 *   pnpm db:types --check  # exit 1 if the committed file is stale
 */
import { PGlite } from "@electric-sql/pglite";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join("src", "db", "database.types.ts");
const check = process.argv.includes("--check");

interface Col { table_name: string; column_name: string; data_type: string; udt_name: string; is_nullable: "YES" | "NO"; column_default: string | null; ordinal_position: number }

function tsType(c: Col): string {
  const map: Record<string, string> = {
    uuid: "string", text: "string", varchar: "string", bpchar: "string",
    int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number",
    bool: "boolean", timestamptz: "string", timestamp: "string", date: "string", jsonb: "Json", json: "Json",
  };
  if (c.data_type === "ARRAY") {
    const inner = map[c.udt_name.replace(/^_/, "")] ?? "unknown";
    return `${inner}[]`;
  }
  return map[c.udt_name] ?? "unknown";
}

const db = new PGlite();
const dir = join(process.cwd(), "supabase", "migrations");
for (const f of readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(join(dir, f), "utf8"));
}
const cols = (
  await db.query<Col>(
    `select table_name, column_name, data_type, udt_name, is_nullable, column_default, ordinal_position
     from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`,
  )
).rows;
await db.close();

const tables = new Map<string, Col[]>();
for (const c of cols) tables.set(c.table_name, [...(tables.get(c.table_name) ?? []), c]);

const lines: string[] = [
  "// Generated by scripts/gen-types.ts from supabase/migrations. Do not edit; run `pnpm db:types`.",
  "",
  "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];",
  "",
  "export type Database = {",
  "  public: {",
  "    Tables: {",
];
for (const [name, cs] of tables) {
  lines.push(`      ${name}: {`);
  lines.push("        Row: {");
  for (const c of cs) lines.push(`          ${c.column_name}: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`);
  lines.push("        };");
  lines.push("        Insert: {");
  for (const c of cs) {
    const optional = c.is_nullable === "YES" || c.column_default !== null;
    lines.push(`          ${c.column_name}${optional ? "?" : ""}: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`);
  }
  lines.push("        };");
  lines.push("        Update: {");
  for (const c of cs) lines.push(`          ${c.column_name}?: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`);
  lines.push("        };");
  lines.push("        Relationships: [];");
  lines.push("      };");
}
lines.push("    };", "    Views: { [_ in never]: never };", "    Functions: { [_ in never]: never };", "    Enums: { [_ in never]: never };", "    CompositeTypes: { [_ in never]: never };", "  };", "};", "");
const out = lines.join("\n");

if (check) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing */ }
  if (current !== out) {
    console.error(`${OUT} is out of date with supabase/migrations. Run: pnpm db:types`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${tables.size} tables)`);
}
